// Server catalog. Output: packages/contracts/src/wish/server-list.generated.ts.
// 1. Global: the official list the PC launcher downloads,
//    https://htkrserverlist1.wmupd.com/patchtest/serverlist_ob40.json (mirror htkrserverlist2; URL from the launcher SDK
//    log HottaLaunch\UserData\Log\newSdkLog\sdk_*.log). Snapshot scripts/data/serverlist_ob40.json; `--fetch` refreshes it.
// 2. China: ServerList.json of the global install (D:\TowerOfFantasy_Global, dated 2026-08-24, GBK), converted to UTF-8 as
//    scripts/data/serverlist_cn.json: { "<server id>": "<name>" }.
// 3. Taiwan: ids observed in profile packets (scripts/data/serverlist_tw.json, { servers: { "<id>": { name, tab } | null } });
//    an unknown name is shown as "#<id>" until the Taiwan launcher's list is found.
const fs = require('node:fs');
const path = require('node:path');
const SOURCE_URL = 'https://htkrserverlist1.wmupd.com/patchtest/serverlist_ob40.json';
const snapshot = path.join(__dirname, '../data/serverlist_ob40.json');
const chinaSnapshot = path.join(__dirname, '../data/serverlist_cn.json');
const taiwanSnapshot = path.join(__dirname, '../data/serverlist_tw.json');
const output = path.resolve(__dirname, '../../packages/contracts/src/wish/server-list.generated.ts');
// In-game tab (ServerRegion) -> site region. The PlayStation tabs (PSNRegion SIEA / SIEE / SIEJA-Japan / SIEJA-Asia) form
// one PS region: the same global game, now also playable from the PC client (2026-10-22). Warp (a separate MMO mode with
// its own characters) and test entries keep their own regions.
const REGIONS = {
  'Asia Pacific': ['Asia-Pacific', 'AP'], 'North America': ['North America', 'NA'], Europe: ['Europe', 'EU'],
  'South America': ['South America', 'SA'], 'Southeast Asia': ['Southeast Asia', 'SEA'], '에스페리아': ['Korea', 'KR'],
  'PS-America': ['PlayStation', 'PS', {platform: 'ps'}], 'PS-Europe': ['PlayStation', 'PS', {platform: 'ps'}],
  'PS-East Asia': ['PlayStation', 'PS', {platform: 'ps'}], 'PS-Southeast Asia': ['PlayStation', 'PS', {platform: 'ps'}],
  'Warp Server': ['Warp Server', 'WS', {kind: 'warp'}],
  TEST: ['Test', 'TEST', {kind: 'test'}], PlayStation: ['Test', 'TEST', {kind: 'test', platform: 'ps'}],
};
const TEST = REGIONS.TEST;

(async () => {
  if (process.argv.includes('--fetch')) {
    const response = await fetch(SOURCE_URL);
    if (!response.ok) throw new Error(`${SOURCE_URL}: ${response.status}`);
    fs.writeFileSync(snapshot, await response.text());
  }
  const servers = {};
  const ports = new Set();
  const add = (id, name, region, tab) => {
    if (!/^\d{4,7}$/.test(id)) throw new Error(`Unexpected server id ${id}`);
    if (servers[id]) throw new Error(`Duplicate server id ${id}`);
    servers[id] = {id, name: name.trim(), region: region[0], regionCode: region[1], tab, ...region[2]};
  };
  // The global file has trailing commas: strip them before parsing.
  for (const row of JSON.parse(fs.readFileSync(snapshot, 'utf8').replace(/,\s*([\]}])/g, '$1'))) {
    const region = row.TestMode ? (row.ServerRegion === 'PlayStation' ? REGIONS.PlayStation : TEST) : REGIONS[row.ServerRegion];
    if (!region) throw new Error(`Unknown server region ${row.ServerRegion} (${row.Name})`);
    add(row.Name, row.SessionName, region, row.ServerRegion);
    if (Number.isInteger(row.Port)) ports.add(row.Port);
  }
  // China: names say what they are; "…测试" (test) entries go to the test region.
  for (const [id, name] of Object.entries(JSON.parse(fs.readFileSync(chinaSnapshot, 'utf8')))) {
    add(id, name, /测试/.test(name) ? [TEST[0], TEST[1], {kind: 'test'}] : ['China', 'CN'], 'China');
  }
  // An entry is null (id seen, name unknown) or { name, tab, region? }: tab is the server-select group (星島, 班吉斯, …);
  // `region` (a REGIONS key) moves it out of Taiwan, as the Taiwan Warp server (躍遷服).
  for (const [id, entry] of Object.entries(JSON.parse(fs.readFileSync(taiwanSnapshot, 'utf8')).servers)) {
    const region = entry?.region ? REGIONS[entry.region] : ['Taiwan', 'TW'];
    if (!region) throw new Error(`Unknown server region ${entry.region} (${id})`);
    add(id, entry?.name ?? `#${id}`, region, entry?.tab ?? 'Taiwan');
  }
  const sorted = Object.fromEntries(Object.entries(servers).sort(([a], [b]) => a.length - b.length || a.localeCompare(b)));
  const jsonOutput = path.resolve(__dirname, '../../apps/web/public/game-data/server-list.json');
  fs.mkdirSync(path.dirname(jsonOutput), {recursive: true});
  fs.writeFileSync(jsonOutput, JSON.stringify(sorted, null, 2) + '\n');
  fs.writeFileSync(output, '// Generated by scripts/generators/build-server-list.cjs from scripts/data/serverlist_ob40.json\n'
    + `// (${SOURCE_URL}) , scripts/data/serverlist_cn.json and serverlist_tw.json. Do not edit by hand.\n`
    + "import type { GameServerInfo } from './servers';\n\n"
    + `export const OFFICIAL_SERVERS: Record<string, GameServerInfo> = ${JSON.stringify(sorted, null, 2)};\n`);
  const counts = {};
  for (const server of Object.values(sorted)) counts[server.tab] = (counts[server.tab] ?? 0) + 1;
  console.log(`Generated ${Object.keys(sorted).length} servers`, counts);
})().catch(error => { console.error(error); process.exitCode = 1; });
