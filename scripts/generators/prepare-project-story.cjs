/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS build entry point, like the other site generators. */
// Editorial media only: the case-study Markdown is maintained separately from game exports.
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {createRequire} = require('node:module');
const root = path.resolve(__dirname, '../..');
const sharp = createRequire(path.join(root, 'apps/web/package.json'))('sharp');
const destination = path.join(root, 'apps/web/public/project-story');

async function main() {
  const markdown = ['case-study.md', 'case-study.ru.md'].map(file => fs.readFileSync(path.join(root, 'docs', file), 'utf8')).join('\n');
  const references = [...new Set([...markdown.matchAll(/\bsrc="((?:screenshots|stickers)\/[a-z0-9-]+\.(?:webp|gif))"/g)].map(match => match[1]))];
  if (!references.length) throw new Error('The project story has no declared media');
  const manifest = {};
  const imports = [];
  const entries = [];
  for (const relative of references) {
    const input = path.join(root, 'docs', relative);
    const output = path.join(destination, relative);
    fs.mkdirSync(path.dirname(output), {recursive:true});
    // Private releases retain these editorial assets in public/. Public clones rebuild them from docs/.
    if (fs.existsSync(input)) fs.copyFileSync(input, output);
    if (!fs.existsSync(output)) throw new Error(`Missing editorial media: ${relative}`);
    const digest = createHash('sha256').update(fs.readFileSync(output)).digest('hex').slice(0,12);
    const metadata = await sharp(output).metadata();
    const asset = {src:`/project-story/${relative}?v=${digest}`, width:metadata.width, height:metadata.pageHeight ?? metadata.height};
    const identifier = `asset${imports.length}`;
    imports.push(`import ${identifier} from ${JSON.stringify(`../../../public/project-story/${relative}`)};`);
    const fields = [`src:${identifier}.src`, `width:${identifier}.width`, `height:${identifier}.height`];
    if (relative.endsWith('.gif')) {
      const poster = output.replace(/\.gif$/, '.poster.webp');
      await sharp(output).webp({lossless:true}).toFile(poster);
      asset.poster = `/project-story/${relative.replace(/\.gif$/, '.poster.webp')}?v=${digest}`;
      const posterIdentifier = `${identifier}Poster`;
      imports.push(`import ${posterIdentifier} from ${JSON.stringify(`../../../public/project-story/${relative.replace(/\.gif$/, '.poster.webp')}`)};`);
      fields.push(`poster:${posterIdentifier}.src`);
    } else {
      const sample = await sharp(output).resize(64,64,{fit:'inside'}).flatten({background:'#000'}).removeAlpha().raw().toBuffer({resolveWithObject:true});
      let nearWhite = 0;
      for (let index = 0; index < sample.data.length; index += sample.info.channels) {
        if (sample.data[index] > 225 && sample.data[index+1] > 225 && sample.data[index+2] > 225) nearWhite++;
      }
      // Editorial white charts/spreadsheets need gentler contrast against the dark reading page.
      if (nearWhite / (sample.info.width * sample.info.height) > 0.4) {
        asset.dimmed = true;
        fields.push('dimmed:true');
      }
    }
    manifest[relative] = asset;
    entries.push(`  ${JSON.stringify(relative)}:{${fields.join(', ')}}`);
  }
  fs.writeFileSync(path.join(destination, 'media.json'), JSON.stringify(manifest, null, 2) + '\n');
  // Static imports let Next bundle these originals in /_next/static/media. They remain
  // available when self-hosted deployments mount their own public/ game-data directory.
  const modulePath = path.join(root, 'apps/web/src/features/project-story/media.generated.ts');
  const moduleSource = `// Generated by prepare-project-story.cjs. Do not edit.\n${imports.join('\n')}\n\nconst media = {\n${entries.join(',\n')}\n};\nexport default media;\n`;
  if (!fs.existsSync(modulePath) || fs.readFileSync(modulePath, 'utf8') !== moduleSource) fs.writeFileSync(modulePath, moduleSource);
  console.log(`Project story: ${references.length} editorial images prepared.`);
}

main().catch(error => {console.error(error); process.exitCode = 1;});
