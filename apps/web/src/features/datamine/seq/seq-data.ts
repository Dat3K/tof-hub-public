export function mergeSeqData(serverData: SeqCacheDataset | null | undefined): SeqStageItem[] {
  if (!serverData || !Array.isArray(serverData.stages) || serverData.stages.length === 0) {
    return BASELINE_SEQ_STAGES.map((stage) => ({
      ...stage,
      portrait: stage.portrait ? gameAsset(stage.portrait, 'webp') : null,
    }));
  }

  const baselineMap = new Map(BASELINE_SEQ_STAGES.map((s) => [s.stage, s]));
  let prevEhp: number | null = null;

  return serverData.stages.map((ss) => {
    const fallback = baselineMap.get(ss.stage) || ({} as Partial<SeqStageItem>);
    const maxHealth = ss.maxHealth ?? fallback.maxHealth ?? 0;
    const isMechAdj = Boolean(ss.isMechanicsAdjusted ?? fallback.isMechanicsAdjusted);
    const effectiveHp = ss.effectiveHp ?? fallback.effectiveHp ?? Math.round(maxHealth * (1 + BASE_RESIST_RATE));

    const powercreep = prevEhp === null ? 0 : ((effectiveHp / prevEhp) - 1) * 100;
    prevEhp = effectiveHp;

    const enemyNameEn = ss.enemyNameEn ?? ss.name_en ?? fallback.enemyNameEn ?? null;
    const enemyNameRu = ss.enemyNameRu ?? ss.name_ru ?? fallback.enemyNameRu ?? null;
    const rawStatus = (ss as any).nameStatus ?? fallback.nameStatus;
    const nameStatus: 'confirmed' | 'unresolved' =
      rawStatus === 'unresolved' || (!enemyNameEn && fallback.nameStatus === 'unresolved')
        ? 'unresolved'
        : 'confirmed';

    let mechNote = '';
    if (typeof ss.mechanics === 'string') {
      mechNote = ss.mechanics;
    } else if (Array.isArray(ss.mechanics)) {
      mechNote = ss.mechanics.join('; ');
    } else {
      mechNote = fallback.mechanicsNote || '';
    }

    return {
      stage: ss.stage,
      codename: ss.codename || fallback.codename || `endless_special_boss_${ss.stage}`,
      enemyCode: ss.enemyCode || fallback.enemyCode || ss.codename || '',
      enemyNameEn,
      enemyNameRu,
      name_en: enemyNameEn,
      name_ru: enemyNameRu,
      nameStatus,
      nameSource: fallback.nameSource || (enemyNameEn ? 'confirmed' : 'unresolved'),
      roomId: fallback.roomId || 'sequential_phantasm',
      roomNameEn: fallback.roomNameEn || 'Sequential Phantasm',
      roomNameRu: fallback.roomNameRu || 'Последовательный фантазм',
      maxHealth,
      effectiveHp,
      atk: ss.atk ?? fallback.atk ?? null,
      def: ss.def ?? fallback.def ?? null,
      crit: ss.crit ?? fallback.crit ?? 0,
      critResist: ss.critResist ?? fallback.critResist ?? (ss.stage <= 21 ? 0.01 : 0),
      element: ss.element || fallback.element || 'Physical',
      portrait: (ss.portrait || fallback.portrait)
        ? gameAsset((ss.portrait || fallback.portrait)!, 'webp')
        : null,
      isMechanicsAdjusted: isMechAdj,
      mechanicsNote: mechNote,
      powercreep,
    };
  });
}
