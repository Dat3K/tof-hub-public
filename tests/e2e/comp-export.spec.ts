test('Auto role follows weapon resonance even after a manual override',async({page})=>{
  await page.goto('/tools/comp/');
  const row=page.getByRole('row').filter({has:page.locator('input[value="Player 1"]')});
  const role=row.locator('[class*="roleBadge"]');
  await expect(role).toContainText('Tank');
  await role.click();
  const dialog=page.getByRole('dialog');
  await expect(dialog.getByRole('button',{name:'Auto (Tank)',exact:true})).toHaveAttribute('aria-pressed','true');
  await dialog.getByRole('button',{name:'DPS (Attack)',exact:true}).click();
  await expect(role).toContainText('DPS');
  await role.click();
  await expect(dialog.getByRole('button',{name:'DPS (Attack)',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(dialog.getByRole('button',{name:'Auto (Tank)',exact:true})).toHaveAttribute('aria-pressed','false');
  await page.screenshot({path:'ignore/documentation-media/generated/comp-role-popover.png',animations:'disabled'});
  await dialog.getByRole('button',{name:'Auto (Tank)',exact:true}).click();
  await expect(role).toContainText('Tank');
});

