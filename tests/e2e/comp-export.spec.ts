test('exports the live trait crop and keeps the signature at the top right',async({page})=>{
  await page.addInitScript(()=>{
    const calls:{src:string;args:number[]}[]=[],texts:{text:string;x:number;y:number}[]=[];
    Object.assign(window,{compExportImages:calls,compExportTexts:texts});
    const draw=CanvasRenderingContext2D.prototype.drawImage,fill=CanvasRenderingContext2D.prototype.fillText;
    CanvasRenderingContext2D.prototype.drawImage=function(...args:Parameters<typeof draw>){
      if(args[0] instanceof HTMLImageElement)calls.push({src:args[0].src,args:args.slice(1) as number[]});
      return Reflect.apply(draw,this,args);
    };
    CanvasRenderingContext2D.prototype.fillText=function(text,x,y,...rest){texts.push({text,x,y});return fill.call(this,text,x,y,...rest);};
  });
  await page.goto('/tools/comp/');
  await page.getByRole('button',{name:'Squad Preset Compositions',exact:true}).click();
  await page.getByRole('option').nth(1).click();
  const portrait=page.locator('[class*="traitAvatar"] img').first();
  await expect(portrait).toBeVisible();
  await expect.poll(()=>portrait.evaluate(img=>(img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  const image=await portrait.evaluate(img=>({src:(img as HTMLImageElement).src,width:(img as HTMLImageElement).naturalWidth,height:(img as HTMLImageElement).naturalHeight,transform:getComputedStyle(img).transform}));
  expect(image.transform).toBe(`matrix(${COMP_TRAIT_IMAGE_SCALE}, 0, 0, ${COMP_TRAIT_IMAGE_SCALE}, 0, 0)`);
  const downloading=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export PNG',exact:true}).click();
  await (await downloading).saveAs('ignore/documentation-media/generated/comp-export-image-parity.png');
  const captured=await page.evaluate(()=>({images:(window as unknown as {compExportImages:{src:string;args:number[]}[]}).compExportImages,texts:(window as unknown as {compExportTexts:{text:string;x:number;y:number}[]}).compExportTexts}));
  const exported=captured.images.find(call=>call.src===image.src)!;
  expect(exported).toBeTruthy();
  const crop=coverImageRect(image.width,image.height,52,52,COMP_TRAIT_IMAGE_SCALE);
  expect(exported.args[2]).toBeCloseTo(crop.width);
  expect(exported.args[3]).toBeCloseTo(crop.height);
  expect(captured.texts.filter(item=>item.text==='@kritik')).toEqual([{text:'@kritik',x:1084,y:38}]);
  await page.screenshot({path:'ignore/documentation-media/generated/comp-live-image-parity.png',animations:'disabled'});
});
