async function sealedFile(request:APIRequestContext,capture:unknown) {
  const response=await request.get('/api/v1/build/import/public-key');expect(response.ok()).toBe(true);
  const pub=await response.json(),key=randomBytes(32),nonce=randomBytes(12),cipher=createCipheriv('aes-256-gcm',key,nonce);
  cipher.setAAD(Buffer.from(`tof-hub-build-sealed:1:${pub.key_id}`));
  const ciphertext=Buffer.concat([cipher.update(JSON.stringify(capture),'utf8'),cipher.final()]);
  return {name:'optimizer.tofbuild',mimeType:'application/octet-stream',buffer:Buffer.from(JSON.stringify({format:'tof-hub-build-sealed',version:1,key_id:pub.key_id,
    wrapped_key:publicEncrypt({key:pub.public_key_pem,padding:constants.RSA_PKCS1_OAEP_PADDING,oaepHash:'sha256'},key).toString('base64url'),nonce:nonce.toString('base64url'),ciphertext:ciphertext.toString('base64url'),tag:cipher.getAuthTag().toString('base64url')}))};
}

