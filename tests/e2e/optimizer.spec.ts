// Check rendered text edges, so different digit lengths and percentages cannot move either numeric column.
async function expectAlignedGearValues(previews:ReturnType<Page['locator']>) {
  const columns=await previews.evaluateAll(lists=>lists.map(list=>{
    const edges=(selector:string)=>Array.from(list.querySelectorAll(selector)).flatMap(node=>{
      if(!node.textContent?.trim())return [];
      const range=document.createRange();range.selectNodeContents(node);
      return [range.getBoundingClientRect().right];
    });
    return {current:edges('[data-stat-value="current"]'),maximum:edges('[data-stat-value="maximum"]'),fits:list.scrollWidth<=list.clientWidth};
  }));
  expect(columns.length).toBeGreaterThan(0);
  for(const column of columns){
    expect(column.fits).toBe(true);
    expect(column.current.length).toBeGreaterThan(0);
    for(const values of [column.current,column.maximum])if(values.length)expect(Math.max(...values)-Math.min(...values)).toBeLessThan(1);
    if(column.maximum.length)expect(Math.min(...column.maximum)).toBeGreaterThan(Math.max(...column.current));
  }
}
