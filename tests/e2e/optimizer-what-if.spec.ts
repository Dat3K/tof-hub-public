  await dialog.getByRole('button',{name:'Try on this state',exact:true}).click();
  await expect(equipment(page).getByText('Temporary · after Titan 98%')).toHaveCount(1);
  await page.getByRole('radio',{name:/^All pieces/}).click();
  const candidate=inventory(page).getByRole('button',{name:new RegExp(`^Try on (?!${slot} )`)}).and(page.locator(':enabled')).first();
  await candidate.focus();await candidate.press('Enter');
  await expect(equipment(page).getByText('Temporary · from backpack')).toHaveCount(1);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await equipment(page).evaluate(node=>window.scrollTo({top:window.scrollY+node.getBoundingClientRect().top-64,behavior:'instant'}));
  await page.screenshot({path:'ignore/documentation-media/generated/optimizer-what-if-mobile.png'});
  await equipment(page).getByRole('button',{name:'Reset all',exact:true}).click();
  await page.getByRole('button',{name:'Language selector: English',exact:true}).click();
  await page.locator('[data-datamine-language="ru"]').click();
