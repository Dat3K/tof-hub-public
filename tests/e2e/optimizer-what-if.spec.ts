import {test,expect,type Page} from '@playwright/test';
import {readFileSync} from 'node:fs';
import type {BuildCatalog} from '../../apps/web/src/features/build/types';

const inventory=(page:Page)=>page.getByRole('list',{name:'Inventory comparison'});
const equipment=(page:Page)=>page.getByRole('region',{name:'Equipped gear',exact:true});
async function helmets(page:Page) {
  await page.goto('/tools/optimizer/');
  await page.getByRole('radio',{name:/^All pieces/}).click();
  await page.getByRole('button',{name:/^(Helmet\s*){1,2}$/}).click();
}
test('temporary swap exchanges build and inventory, recalculates deltas, and restores the baseline',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await helmets(page);
  const stats=await page.getByRole('table',{name:'Combat stats'}).innerText();
  const storage=await page.evaluate(()=>localStorage.getItem('tof-optimizer-session-v1'));
  const heading=equipment(page).locator('h2');
  const geometry=await heading.evaluate(node=>{const box=node.getBoundingClientRect();return {x:box.x,y:box.y+window.scrollY,width:box.width,height:box.height};});
  await inventory(page).getByRole('button',{name:'Try on Helmet demo-helmet-plain',exact:true}).click();
  await expect(equipment(page).getByText('Temporary · from backpack')).toBeVisible();
  await expect(equipment(page).getByText(/Temporary changes/)).toContainText('1');
  await expect(inventory(page).getByRole('article',{name:'Helmet · demo-helmet-plain'})).toHaveCount(0);
  const original=inventory(page).getByRole('article',{name:'Helmet · equipped-helmet'});
  await expect(original).toBeVisible();
  await expect(original.getByText('Equipped (real)')).toBeVisible();
  await expect(equipment(page).getByLabel('Total rating: real → temporary')).toBeVisible();
  await expect.poll(()=>page.getByRole('table',{name:'Combat stats'}).innerText()).not.toBe(stats);
  expect(await heading.evaluate(node=>{const box=node.getBoundingClientRect();return {x:box.x,y:box.y+window.scrollY,width:box.width,height:box.height};})).toEqual(geometry);
  expect(await page.evaluate(()=>localStorage.getItem('tof-optimizer-session-v1'))).toBe(storage);
  await original.getByRole('button',{name:'Try on Helmet equipped-helmet'}).click();
  await expect(equipment(page).getByText(/Temporary ·/)).toHaveCount(0);
  await expect(inventory(page).getByRole('article',{name:'Helmet · demo-helmet-plain'})).toBeVisible();
  await expect.poll(()=>page.getByRole('table',{name:'Combat stats'}).innerText()).toBe(stats);
  expect(errors).toEqual([]);
});
test('forecast from Compare follows the target; reset and direct reload discard all temporary state',async({page})=>{
  await helmets(page);
  await inventory(page).getByRole('button',{name:'Compare Helmet demo-helmet-plain',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Gear comparison'});
  await dialog.getByRole('radio',{name:'After transfer · 98%',exact:true}).click();
  await dialog.getByRole('button',{name:'Try on this state',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const helmet=equipment(page).getByRole('region',{name:'Helmet',exact:true});
  await expect(helmet.getByText('Temporary · after Titan 98%')).toBeVisible();
  const old=await helmet.innerText();
  const input=page.getByRole('spinbutton',{name:'Titan target percent',exact:true});
  await input.fill('90');await input.press('Enter');
  await expect(helmet.getByText('Temporary · after Titan 90%')).toBeVisible();
  expect(await helmet.innerText()).not.toBe(old);
  await equipment(page).evaluate(node=>window.scrollTo({top:window.scrollY+node.getBoundingClientRect().top-64,behavior:'instant'}));
  await page.screenshot({path:'ignore/documentation-media/generated/optimizer-what-if-desktop.png'});
  await equipment(page).getByRole('button',{name:'Reset all',exact:true}).click();
  await expect(helmet.getByText(/Temporary ·/)).toHaveCount(0);
  await inventory(page).getByRole('button',{name:'Try on Helmet demo-helmet-plain',exact:true}).click();
  await page.reload();
  await expect(equipment(page)).toBeVisible();
  await expect(equipment(page).getByText(/Temporary ·/)).toHaveCount(0);
  await expect(equipment(page).getByRole('button',{name:'Reset all',exact:true})).toHaveCount(0);
});
