test('current nicknames survive fast toggles, a failed refresh batch and cache expiry', async ({page}) => {
  await page.clock.install();
  let refresh = false, authoritativeEmpty = false, started = 0;
  let release!: () => void;
  const delayed = new Promise<void>(resolve => {release = resolve;});
  await page.route('**/api/v1/ranking/player-names', async route => {
    const {identifiers = []} = route.request().postDataJSON() as {identifiers: string[]};
    if (!refresh) {started++; await delayed;}
    if (refresh && !authoritativeEmpty && identifiers.includes('47300474936903')) return route.fulfill({status: 503, json: {code: 'SERVER_BUSY'}});
    return route.fulfill({json: {available: true, entries: authoritativeEmpty ? [] : identifiers.map(identifier => ({identifier, uid: identifier, nickname: `Current ${identifier}`, observedAt: '2026-10-28T10:00:00.000Z'}))}});
  });
  await page.goto('/datamine/raids/?tab=ranking&season=S16&region=AP&lang=en', {waitUntil: 'domcontentloaded'});
  const ranking = page.getByRole('region', {name: 'Raid rankings', exact: true});
  await expect(page.locator('[data-ranking-ready="true"]')).toBeVisible({timeout: 60000});
  const toggle = ranking.getByRole('button', {name: 'Current nicknames', exact: true});
  await toggle.click();
  await expect.poll(() => started).toBeGreaterThan(0);
  await toggle.click(); await toggle.click(); await toggle.click(); await toggle.click();
  release();
  const name = ranking.getByRole('button', {name: 'Current 47300474936903', exact: true}).first();
  await expect(name).toBeVisible();
  refresh = true;
  await page.clock.fastForward(61000);
  const refused = page.waitForResponse(response => response.url().endsWith('/api/v1/ranking/player-names') && response.status() === 503);
  await toggle.click(); await toggle.click();
  await refused;
  await page.clock.runFor(100);
  // The failed group must not erase names already obtained for it or successful groups.
  await expect(name).toBeVisible();
  await expect(ranking.getByRole('button', {name: 'Current 47287589983277', exact: true}).first()).toBeVisible();
  await toggle.click(); await expect(ranking.getByRole('button', {name: 'Sr1ver', exact: true}).first()).toBeVisible();
  await toggle.click(); await expect(name).toBeVisible();
  authoritativeEmpty = true;
  await page.clock.fastForward(61000);
  await toggle.click(); await toggle.click();
  await expect(ranking.getByRole('button', {name: 'Sr1ver', exact: true}).first()).toBeVisible();
});

