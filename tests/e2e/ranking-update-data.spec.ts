import {test,expect} from '@playwright/test';

test('update data explains both capture paths and uploads through the existing queue',async({page})=>{
  let loads=0;
  await page.route('**/api/v1/ranking/**',route=>{
    if(route.request().method()==='POST')return route.fulfill({json:{id:'players-update',kind:'players-import',state:'complete',createdAt:new Date().toISOString(),result:{stored:1,duplicates:0,rejected:0,files:1}}});
    loads++;return route.fulfill({json:{available:true,total:0,overall:0,databaseEmpty:false,entries:[]}});
  });
  let buildPosted=false;
  await page.route('**/api/v1/build/import',route=>{buildPosted=true;return route.fulfill({json:{id:'build-update',kind:'build-import',state:'complete',createdAt:new Date().toISOString(),result:{}}});});
  await page.goto('/tools/ranking/?board=players&track=all');
  const trigger=page.getByRole('button',{name:'Update data',exact:true});
  await trigger.click();
  let modal=page.getByRole('dialog',{name:'Update data',exact:true});
  await expect(modal.getByRole('heading',{name:'Capture your own build'})).toBeVisible();
  await expect(modal.getByRole('heading',{name:'Ask another player'})).toBeVisible();
  await expect(modal).toContainText('only files from the capture app');
  await expect(modal.getByText('How it works',{exact:true})).toHaveCount(0);
  const buttons=modal.getByRole('button',{name:/How to collect/});
  const positions=await buttons.evaluateAll(nodes=>nodes.map(node=>node.getBoundingClientRect().top));
  expect(Math.abs(positions[0]!-positions[1]!)).toBeLessThan(1);
  await page.screenshot({path:'ignore/documentation-media/generated/ranking-update-data-en.png',animations:'disabled'});
  const before=loads;
  await modal.getByRole('button',{name:'How to collect .tofbuild',exact:true}).click();
  modal=page.getByRole('dialog',{name:'Collect your build card and pull history',exact:true});
  await expect(modal.getByRole('heading',{name:'How it works',exact:true})).toBeVisible();
  const buildChooser=page.waitForEvent('filechooser');
  await modal.getByRole('button',{name:'Upload .tofbuild',exact:true}).click();
  await (await buildChooser).setFiles({name:'fresh.tofbuild',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'tof-hub-build-sealed'}))});
  await expect(page.getByRole('status').filter({hasText:'Build uploaded.'})).toBeVisible();
  expect(buildPosted).toBe(true);await expect.poll(()=>loads).toBeGreaterThan(before);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Language selector: English',exact:true}).click();
  await page.locator('[data-datamine-language="ru"]').click();
  await page.getByRole('button',{name:'Обновить данные',exact:true}).click();
  modal=page.getByRole('dialog',{name:'Обновить данные',exact:true});
  await expect(modal.getByRole('heading',{name:'Соберите свой билд'})).toBeVisible();
  await expect(modal.getByRole('heading',{name:'Попросите другого игрока'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'ignore/documentation-media/generated/ranking-update-data-ru-mobile.png',animations:'disabled'});
  await modal.getByRole('button',{name:'Как собрать .tofplayers',exact:true}).click();
  modal=page.getByRole('dialog',{name:'Соберите карточку билда и историю круток',exact:true});
  const playersChooser=page.waitForEvent('filechooser');
  await modal.getByRole('button',{name:'Загрузить .tofplayers',exact:true}).click();
  await (await playersChooser).setFiles({name:'fresh.tofplayers',mimeType:'application/octet-stream',buffer:Buffer.from(JSON.stringify({format:'tof-hub-players-sealed'}))});
  await expect(page.getByRole('status').filter({hasText:'Игроков: 1'})).toBeVisible();
  await page.getByRole('button',{name:'Обновить данные',exact:true}).click();
  modal=page.getByRole('dialog',{name:'Обновить данные',exact:true});
  await page.keyboard.press('Escape');
  await expect(modal).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Обновить данные',exact:true})).toBeFocused();
});
