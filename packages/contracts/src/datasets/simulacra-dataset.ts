import { z } from 'zod';

export const SimulacraDatasetItemRawSchema = z.object({
  id: z.string(),
  avatar_id: z.string().optional(),
  imitation_id: z.string().optional(),
  weapon_id: z.string().optional(),
  matrix_suit_id: z.string().nullable().optional(),
  matrix_suit_num: z.number().nullable().optional(),
  name_en: z.string().optional(),
  name_ru: z.string().optional(),
  name: z.string().optional(),
  weapon_name_en: z.string().optional(),
  weapon_name_ru: z.string().optional(),
  weapon_name: z.string().optional(),
  element: z.string().optional(),
  element_secondary: z.string().nullable().optional(),
  element_combo_icon: z.string().nullable().optional(),
  role: z.string().optional(),
  role_icon: z.string().nullable().optional(),
  resonance: z.string().nullable().optional(),
  rarity: z.string().optional(),
  server_mode: z.string().optional(),
  edition: z.string().optional(),
  has_matrices: z.boolean().optional(),
  no_matrices: z.boolean().optional(),
  season: z.union([z.string(), z.number()]).nullable().optional(),
  season_tag: z.union([z.string(), z.number()]).nullable().optional(),
  season_badge: z.union([z.string(), z.number()]).nullable().optional(),
  avatar: z.string().optional(),
  avatar_thumb: z.string().optional(),
  portrait: z.string().optional(),
  portrait_thumb: z.string().optional(),
  detail_art: z.string().optional(),
  detail_art_thumb: z.string().optional(),
  card: z.string().optional(),
  card_thumb: z.string().optional(),
  art_focus: z.string().nullable().optional(),
  icon: z.string().optional(),
  icon_thumb: z.string().optional(),
  base_stats: z.record(z.string(), z.unknown()).optional(),
  max_stats: z.record(z.string(), z.unknown()).optional(),
  advancements: z.array(z.record(z.string(), z.unknown())).optional(),
  traits: z.array(z.record(z.string(), z.unknown())).optional(),
  affinity_ladder: z.array(z.record(z.string(), z.unknown())).optional(),
  weapon: z.record(z.string(), z.unknown()).optional(),
  matrix: z.record(z.string(), z.unknown()).nullable().optional(),
  coefficients: z.record(z.string(), z.unknown()).optional(),
  media: z.record(z.string(), z.unknown()).nullable().optional(),
  sources: z.record(z.string(), z.unknown()).nullable().optional(),
  assets: z.array(z.record(z.string(), z.unknown())).optional(),
  provenance: z.record(z.string(), z.unknown()).nullable().optional(),
  data_warnings: z
    .array(
      z.object({
        id: z.string(),
        severity: z.literal('warning'),
        title_en: z.string(),
        title_ru: z.string(),
        message_en: z.string(),
        message_ru: z.string(),
        paths: z.array(z.string()),
      }),
    )
    .optional(),
}).passthrough();
export type SimulacraDatasetItemRaw = z.infer<typeof SimulacraDatasetItemRawSchema>;

export const SimulacraDatasetSchema = z.object({
  schemaVersion: z.number().optional(),
  generatedAt: z.string().optional(),
  total: z.number().int().nonnegative(),
  counts: z.record(z.string(), z.number()).optional(),
  diagnostics: z.record(z.string(), z.unknown()).optional(),
  items: z.array(SimulacraDatasetItemRawSchema),
  gacha: z.array(SimulacraDatasetItemRawSchema).optional(),
  mmo: z.array(SimulacraDatasetItemRawSchema).optional(),
});
export type SimulacraDataset = z.infer<typeof SimulacraDatasetSchema>;
