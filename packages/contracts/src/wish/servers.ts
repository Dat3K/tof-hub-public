/**
 * Tower of Fantasy server catalog by Server ID: the official list (generated by scripts/generators/build-server-list.cjs, see
 * docs/imports.md "Official server list") over the legacy entries. A player's UID starts with its server's ID.
 */
export const TOWER_OF_FANTASY_SERVERS: Record<string, GameServerInfo> = { ...LEGACY_SERVERS, ...OFFICIAL_SERVERS };

/** ID lengths in the catalog, longest first (7-digit PlayStation and Esperia ids before the 5-digit ones). */
const SERVER_ID_LENGTHS = [...new Set(Object.keys(TOWER_OF_FANTASY_SERVERS).map(id => id.length))].sort((a, b) => b - a);

/**
 * Resolves Tower of Fantasy server information from a character UID: the longest catalog ID the UID starts with
 * (7 digits for PlayStation and Esperia, otherwise 5).
 *
 * @param uid The in-game character UID (string or number, e.g. "130024918" or "120050012")
 * @returns GameServerInfo or null if not found
 */
export function resolveServerFromUid(uid: string | number | null | undefined): GameServerInfo | null {
  if (!uid) return null;
  const cleaned = String(uid).trim();
  for (const length of SERVER_ID_LENGTHS) {
    const server = cleaned.length > length ? TOWER_OF_FANTASY_SERVERS[cleaned.slice(0, length)] : undefined;
    if (server) return server;
  }
  return null;
}

/** Character UID without the artificial local-number padding emitted by Capture <= 2.0.0. */
export function canonicalPlayerUid(uid:string,{roleId,serverId}:{roleId?:string|null;serverId?:string|null}={}):string {
  if(!/^\d+$/.test(uid))return uid;
  if(roleId&&/^[1-9]\d{0,23}$/.test(roleId)) {
    const role=BigInt(roleId),high=String(role>>32n),low=role&0xffffffffn;
    const local=uid.slice(high.length);
    if(low>0n&&uid.startsWith(high)&&/^\d+$/.test(local)&&BigInt(local)===low)return high+String(low);
  }
  const server=(serverId?getServerById(serverId):null)??resolveServerFromUid(uid);
  if(!server||!uid.startsWith(server.id))return uid;
  const local=uid.slice(server.id.length);
  return /^0+[1-9]\d*$/.test(local)?server.id+local.replace(/^0+/,''):uid;
}

/**
 * Region of a UID whose server is not in the catalog yet (a server newer than the list snapshot): the longest prefix
 * (5 down to 2 digits) whose listed servers all share one region. Taiwan ids (11500NN) share 11500, so a new Taiwan
 * server is not taken for Asia Pacific (11xxx) — the two digits alone are mixed there (2026-10-09).
 */
export function resolveRegionFromUid(uid: string | number | null | undefined): ServerRegionCode | null {
  const server = resolveServerFromUid(uid);
  if (server) return server.regionCode;
  const cleaned = uid ? String(uid).trim() : '';
  if (cleaned.length < 5) return null;
  // From 6 digits: 7-digit ids share 5-digit prefixes across regions (Taiwan 1150004 vs Taiwan Warp 1150013).
  for (let length = 6; length >= 2; length--) {
    const regions = new Set(Object.values(TOWER_OF_FANTASY_SERVERS).filter(item => item.id.startsWith(cleaned.slice(0, length))).map(item => item.regionCode));
    if (regions.size === 1) return [...regions][0]!;
    if (regions.size > 1) return null;
  }
  return null;
}

/**
 * Server and region of a player, the one policy of every import (wish history, build cards, players files): an
 * explicit catalog server id first, then the server the UID starts with, then the region of the UID prefix for a server
 * newer than the catalog. Unknown parts are null.
 */
export function resolvePlayerServer({ uid, serverId }: { uid?: string | number | null; serverId?: string | null }): {
  server: GameServerInfo | null;
  regionCode: ServerRegionCode | null;
} {
  const server = (serverId ? getServerById(serverId) : null) ?? resolveServerFromUid(uid);
  return { server, regionCode: server?.regionCode ?? resolveRegionFromUid(uid) };
}

export type PlayerServerRefusal = 'unknown-server' | 'unsupported-game';
/**
 * Why live player data must not be stored, or null when it may: the server has to be in the catalog (an unknown or
 * newer server cannot be verified) and must not be a Warp/MMO server. Showing the data is never restricted by this.
 */
export function playerServerRefusal(identity: { uid?: string | number | null; serverId?: string | null }): PlayerServerRefusal | null {
  const { server } = resolvePlayerServer(identity);
  if (!server) return 'unknown-server';
  return UNSUPPORTED_GAME_REGION_CODES.includes(server.regionCode) ? 'unsupported-game' : null;
}

/**
 * Gets server information directly by Server ID.
 */
export function getServerById(serverId: string): GameServerInfo | null {
  return TOWER_OF_FANTASY_SERVERS[serverId] ?? null;
}

/**
 * Gets all registered servers belonging to a given region or region code.
 */
export function getServersByRegion(regionOrCode: ServerRegion | ServerRegionCode): GameServerInfo[] {
  return Object.values(TOWER_OF_FANTASY_SERVERS).filter(
    (s) => s.region === regionOrCode || s.regionCode === regionOrCode
  );
}

/**
 * Returns all registered Tower of Fantasy servers.
 */
export function getAllServers(): GameServerInfo[] {
  return Object.values(TOWER_OF_FANTASY_SERVERS);
}

/**
 * Formats a server display string, e.g. "Alintheus (EU)" or "Astra [아스트라] (KR)"
 */
export function formatServerDisplay(
  server: GameServerInfo | null | undefined,
  includeId = false
): string {
  if (!server) return 'Unknown Server';
  const nativePart = server.nativeName ? ` [${server.nativeName}]` : '';
  const idPart = includeId ? ` #${server.id}` : '';
  return `${server.name}${nativePart} (${server.regionCode})${idPart}`;
}
