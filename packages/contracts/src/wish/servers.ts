/**
 * Warp (WS): the separate MMO mode with its own characters. The site does not show its profiles yet (2026-10-14), so no
 * wish history, build profile or ranking data from these servers is stored; viewing a file locally stays possible.
 */
export const UNSUPPORTED_GAME_REGION_CODES: readonly ServerRegionCode[] = ['WS'];
export type ServerRegionCode = z.infer<typeof ServerRegionCodeSchema>;

export interface GameServerInfo {
  /** Server ID: 5 digits (e.g. '13002'), 7 for PlayStation and Esperia ('2001001', '9999101'); the UID starts with it. */
  id: string;
  /** Official English server name */
  name: string;
  /** Server region group */
  region: ServerRegion;
  /** Standard abbreviation for the region */
  regionCode: ServerRegionCode;
  /** Optional localized native name (e.g. Korean or Traditional Chinese) */
  nativeName?: string;
  /** In-game server-select tab of the official list (e.g. 'Asia Pacific', 'PS-America', '에스페리아'). */
  tab?: string;
  /** 'ps' for the PlayStation servers (all of them form the PS region). */
  platform?: 'ps';
  /** Warp (separate MMO mode) or test server. */
  kind?: 'warp' | 'test';
}

